    /**
     * @param  list<array{0: string, 1: string, 2: string}>  $stages
     * @return array<string, mixed>
     */
    private function funnel(string $name, string $description, array $stages): array
    {
        return [
            'name' => $name,
            'description' => $description,
            'stages' => array_map(
                fn (array $stage): array => [
                    'name' => $stage[0],
                    'action' => $stage[1],
                    'color' => $stage[2],
                ],
                $stages
            ),
        ];
    }

    /**
     * @param  list<string>  $options
     * @return array<string, mixed>
     */
    private function selectField(
        string $name,
        array $options,
        ?string $stageName = null,
        ?string $funnelName = null
    ): array {
        return $this->field([
            'name' => $name,
            'value_type' => ProjectSkkField::VALUE_SELECT,
            'options' => $options,
            'stage_name' => $stageName,
            'funnel_name' => $funnelName,
            'show_in_card' => true,
            'show_in_list' => true,
            'show_in_filter' => true,
        ]);
    }

