    public function run(): void
    {
        $writer = app(StarterPackageWriter::class);

        foreach ($this->packages() as $index => $payload) {
            $payload['sort_order'] = $index + 1;
            $payload['is_active'] = true;

            $existing = StarterPackage::query()
                ->where('name', $payload['name'])
                ->first();

            if ($existing) {
                $writer->update($existing, $payload);
            } else {
                $writer->create($payload);
            }
        }
    }

